-- Ingest gateway (INGEST-02): sources and keys, the durable inbox, the outbox of canonical events and the quarantine.
-- Own Flyway history in schema ingest. The schema is created and owned by castor_gateway (db/init/01-roles.sql), the role
-- the service runs as, so no grants are needed. Dev Services and tests use one superuser and let Flyway create the schema.
-- port_id is the port code of the URL (ref.port.code in castor-core): the gateway never reads castor-core's tables.

CREATE TABLE ingest.integration_source (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id           text        NOT NULL
        CONSTRAINT integration_source_port_format CHECK (port_id ~ '^[a-z0-9-]{2,40}$'),
    code              text        NOT NULL
        CONSTRAINT integration_source_code CHECK (code IN ('canonical', 'cbas', 'itap', 'scss', 'edic', 'sensors')),
    enabled           boolean     NOT NULL DEFAULT false,
    require_signature boolean     NOT NULL DEFAULT false,
    -- Name of the configuration entry that holds the HMAC secret; the secret itself is never stored here
    hmac_secret_ref   text,
    quality_default   text        NOT NULL DEFAULT 'OBSERVED'
        CONSTRAINT integration_source_quality CHECK (quality_default IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
    -- Longest accepted age per event type, as ISO-8601 durations: {"equipment.position.observed": "PT30S"}
    freshness_sla     jsonb       NOT NULL DEFAULT '{}'::jsonb
        CONSTRAINT integration_source_sla_object CHECK (jsonb_typeof(freshness_sla) = 'object'),
    created_at        timestamptz NOT NULL,
    updated_at        timestamptz NOT NULL,
    UNIQUE (port_id, code),
    CONSTRAINT integration_source_signature_needs_secret CHECK (NOT require_signature OR hmac_secret_ref IS NOT NULL)
);

-- Keys are random 32-byte values shown once when created; only their SHA-256 hash is kept. origin 'env' marks the key
-- of GATEWAY_DEMO_KEY, which local, dev and test write at start.
CREATE TABLE ingest.api_key (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id  bigint      NOT NULL REFERENCES ingest.integration_source (id) ON DELETE CASCADE,
    prefix     text        NOT NULL,
    key_hash   bytea       NOT NULL CONSTRAINT api_key_hash_length CHECK (octet_length(key_hash) = 32),
    origin     text        NOT NULL DEFAULT 'issued' CONSTRAINT api_key_origin CHECK (origin IN ('issued', 'env')),
    created_at timestamptz NOT NULL,
    revoked_at timestamptz,
    UNIQUE (source_id, key_hash)
);

-- Every accepted record. A row is never deleted: its unique key is what answers a repeat with "duplicate". Housekeeping
-- only empties raw (NORMALIZED after 7 days, QUARANTINED when its quarantine entry expires).
CREATE TABLE ingest.inbox (
    reception_id    uuid        PRIMARY KEY,
    port_id         text        NOT NULL,
    source          text        NOT NULL,
    source_event_id text        NOT NULL,
    received_at     timestamptz NOT NULL,
    raw             jsonb,
    status          text        NOT NULL DEFAULT 'RECEIVED'
        CONSTRAINT inbox_status CHECK (status IN ('RECEIVED', 'NORMALIZED', 'QUARANTINED')),
    normalized_at   timestamptz,
    UNIQUE (port_id, source, source_event_id)
);

-- The normalizer takes RECEIVED rows oldest first (reception ids are time-ordered UUIDv7)
CREATE INDEX inbox_received ON ingest.inbox (reception_id) WHERE status = 'RECEIVED';
-- Housekeeping finds the raw payloads to empty
CREATE INDEX inbox_raw_expiry ON ingest.inbox (normalized_at) WHERE raw IS NOT NULL AND status = 'NORMALIZED';

-- Canonical events waiting for, or past, publication. id is the publication order. (reception_id, event_index) is
-- unique and event_id is derived from it, so normalizing a record again can only produce the same rows.
CREATE TABLE ingest.outbox (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    reception_id uuid        NOT NULL REFERENCES ingest.inbox (reception_id),
    event_index  integer     NOT NULL CONSTRAINT outbox_event_index CHECK (event_index >= 0),
    event_id     uuid        NOT NULL UNIQUE,
    port_id      text        NOT NULL,
    aggregate_id text        NOT NULL,
    event_type   text        NOT NULL,
    payload      jsonb       NOT NULL,
    created_at   timestamptz NOT NULL,
    published_at timestamptz,
    UNIQUE (reception_id, event_index)
);

CREATE INDEX outbox_unpublished ON ingest.outbox (id) WHERE published_at IS NULL;
CREATE INDEX outbox_published ON ingest.outbox (published_at) WHERE published_at IS NOT NULL;

CREATE TABLE ingest.quarantine (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    reception_id uuid        NOT NULL UNIQUE REFERENCES ingest.inbox (reception_id),
    reason_code  text        NOT NULL,
    detail       text        NOT NULL,
    created_at   timestamptz NOT NULL
);

CREATE INDEX quarantine_created ON ingest.quarantine (created_at);
