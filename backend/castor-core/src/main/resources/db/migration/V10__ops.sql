-- Operational state (STATE-01): what is happening in the port, kept apart from the layout (what the port is).
-- Rules: port_id on every table; every operational value carries quality, source and observed_at; a missing value is
-- NULL (unknown), never 0; units are explicit columns; cargo families are rows of ref.cargo_family, not code.
-- Runs as castor_flyway; the application role gets its rights from the default privileges set below.

CREATE SCHEMA IF NOT EXISTS ops;

-- ---------------------------------------------------------------------------------------------------------------
-- Role OPERATOR and the default unit of a cargo family
-- ---------------------------------------------------------------------------------------------------------------

ALTER TABLE security.user_role DROP CONSTRAINT user_role_role_check;
ALTER TABLE security.user_role
    ADD CONSTRAINT user_role_role_check CHECK (role IN ('VIEWER', 'OPERATOR', 'EDITOR', 'PUBLISHER', 'ADMIN'));

-- V3 already seeded the families; CONTAINER stays (ref.cargo_type points at it) and any later family is a row.
ALTER TABLE ref.cargo_family
    ADD COLUMN default_unit varchar(16);
UPDATE ref.cargo_family
SET default_unit = CASE code
                       WHEN 'LIQUID_BULK' THEN 'CUBIC_METRES'
                       WHEN 'RORO' THEN 'VEHICLES'
                       WHEN 'CONTAINER' THEN 'PIECES'
                       ELSE 'TONNES' END;
ALTER TABLE ref.cargo_family
    ALTER COLUMN default_unit SET NOT NULL;
ALTER TABLE ref.cargo_family
    ADD CONSTRAINT cargo_family_default_unit CHECK (default_unit IN ('TONNES', 'PIECES', 'CUBIC_METRES', 'VEHICLES'));

-- ---------------------------------------------------------------------------------------------------------------
-- Vessel calls
-- ---------------------------------------------------------------------------------------------------------------

CREATE TABLE ops.vessel_call
(
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    port_id          bigint       NOT NULL REFERENCES ref.port (id),
    call_code        varchar(64)  NOT NULL,
    vessel_name      varchar(120),
    imo              char(7) CHECK (imo ~ '^[0-9]{7}$'),
    loa_m            numeric(6, 1) CHECK (loa_m > 0),
    beam_m           numeric(5, 1) CHECK (beam_m > 0),
    status           varchar(12)  NOT NULL CHECK (status IN ('EXPECTED', 'ALONGSIDE', 'DEPARTED', 'CANCELLED')),
    eta              timestamptz,
    ata              timestamptz,
    etd              timestamptz,
    atd              timestamptz,
    berth_asset_id   uuid REFERENCES layout.asset (id),
    source           varchar(64)  NOT NULL,
    quality          varchar(12)  NOT NULL CHECK (quality IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
    observed_at      timestamptz  NOT NULL,
    last_occurred_at timestamptz  NOT NULL,
    version          bigint       NOT NULL DEFAULT 0,
    UNIQUE (port_id, call_code)
);

CREATE INDEX vessel_call_berth ON ops.vessel_call (port_id, berth_asset_id);

-- ---------------------------------------------------------------------------------------------------------------
-- Equipment: the latest state and the busy/idle history
-- ---------------------------------------------------------------------------------------------------------------

CREATE TABLE ops.equipment_state
(
    port_id              bigint      NOT NULL REFERENCES ref.port (id),
    asset_id             uuid        NOT NULL REFERENCES layout.asset (id),
    status               varchar(12) NOT NULL
        CHECK (status IN ('WORKING', 'IDLE', 'BLOCKED', 'STARVED', 'DOWN', 'MAINTENANCE')),
    status_reason        text,
    position             geometry(Point, 4326),
    heading_deg          numeric(5, 2) CHECK (heading_deg >= 0 AND heading_deg < 360),
    position_accuracy_m  numeric(7, 2) CHECK (position_accuracy_m >= 0),
    position_observed_at timestamptz,
    assignment           jsonb,
    source               varchar(64) NOT NULL,
    quality              varchar(12) NOT NULL CHECK (quality IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
    observed_at          timestamptz NOT NULL,
    last_occurred_at     timestamptz NOT NULL,
    last_source_sequence bigint,
    version              bigint      NOT NULL DEFAULT 0,
    PRIMARY KEY (port_id, asset_id),
    -- A position never arrives without the time it was observed
    CHECK (position IS NULL OR position_observed_at IS NOT NULL)
);

CREATE INDEX equipment_state_position_gist ON ops.equipment_state USING gist (position);

CREATE TABLE ops.equipment_status_interval
(
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id    bigint      NOT NULL REFERENCES ref.port (id),
    asset_id   uuid        NOT NULL REFERENCES layout.asset (id),
    status     varchar(12) NOT NULL
        CHECK (status IN ('WORKING', 'IDLE', 'BLOCKED', 'STARVED', 'DOWN', 'MAINTENANCE')),
    reason     text,
    started_at timestamptz NOT NULL,
    ended_at   timestamptz,
    source     varchar(64) NOT NULL,
    quality    varchar(12) NOT NULL CHECK (quality IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
    CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- At most one open interval per machine
CREATE UNIQUE INDEX equipment_status_interval_open ON ops.equipment_status_interval (port_id, asset_id)
    WHERE ended_at IS NULL;
CREATE INDEX equipment_status_interval_history ON ops.equipment_status_interval (port_id, asset_id, started_at DESC);

-- ---------------------------------------------------------------------------------------------------------------
-- Cargo lots and their movements
-- ---------------------------------------------------------------------------------------------------------------

CREATE TABLE ops.cargo_lot
(
    id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    port_id              bigint        NOT NULL REFERENCES ref.port (id),
    lot_code             varchar(64)   NOT NULL,
    consignment_code     varchar(64),
    cargo_family         varchar(16)   NOT NULL REFERENCES ref.cargo_family (code),
    commodity            varchar(120)  NOT NULL,
    unit                 varchar(16)   NOT NULL CHECK (unit IN ('TONNES', 'PIECES', 'CUBIC_METRES', 'VEHICLES')),
    registered_quantity  numeric(14, 3) CHECK (registered_quantity >= 0),
    mass_basis           varchar(3) CHECK (mass_basis IN ('WET', 'DRY')),
    current_location_id  uuid REFERENCES layout.asset (id),
    location_occurred_at timestamptz,
    source               varchar(64)   NOT NULL,
    quality              varchar(12)   NOT NULL CHECK (quality IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
    version              bigint        NOT NULL DEFAULT 0,
    UNIQUE (port_id, lot_code)
);

CREATE INDEX cargo_lot_location ON ops.cargo_lot (port_id, current_location_id);

CREATE TABLE ops.cargo_movement
(
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id     bigint         NOT NULL REFERENCES ref.port (id),
    lot_id      uuid           NOT NULL REFERENCES ops.cargo_lot (id),
    from_id     uuid REFERENCES layout.asset (id),
    to_id       uuid           NOT NULL REFERENCES layout.asset (id),
    quantity    numeric(14, 3) NOT NULL CHECK (quantity > 0),
    unit        varchar(16)    NOT NULL CHECK (unit IN ('TONNES', 'PIECES', 'CUBIC_METRES', 'VEHICLES')),
    handled_by  uuid REFERENCES layout.asset (id),
    occurred_at timestamptz    NOT NULL,
    event_id    uuid           NOT NULL UNIQUE
);

CREATE INDEX cargo_movement_lot ON ops.cargo_movement (lot_id, occurred_at);

-- ---------------------------------------------------------------------------------------------------------------
-- Storage inventory and its adjustments
-- ---------------------------------------------------------------------------------------------------------------

CREATE TABLE ops.storage_inventory
(
    port_id              bigint         NOT NULL REFERENCES ref.port (id),
    storage_asset_id     uuid           NOT NULL REFERENCES layout.asset (id),
    commodity            varchar(120)   NOT NULL,
    unit                 varchar(16)    NOT NULL CHECK (unit IN ('TONNES', 'PIECES', 'CUBIC_METRES', 'VEHICLES')),
    quantity             numeric(14, 3) NOT NULL CHECK (quantity >= 0),
    quantity_observed_at timestamptz    NOT NULL,
    source               varchar(64)    NOT NULL,
    quality              varchar(12)    NOT NULL CHECK (quality IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
    version              bigint         NOT NULL DEFAULT 0,
    PRIMARY KEY (port_id, storage_asset_id, commodity)
);

CREATE TABLE ops.inventory_adjustment
(
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id          bigint         NOT NULL REFERENCES ref.port (id),
    storage_asset_id uuid           NOT NULL REFERENCES layout.asset (id),
    commodity        varchar(120)   NOT NULL,
    delta            numeric(14, 3) NOT NULL,
    unit             varchar(16)    NOT NULL CHECK (unit IN ('TONNES', 'PIECES', 'CUBIC_METRES', 'VEHICLES')),
    reason           text           NOT NULL,
    event_id         uuid           NOT NULL UNIQUE,
    occurred_at      timestamptz    NOT NULL
);

CREATE INDEX inventory_adjustment_storage ON ops.inventory_adjustment (port_id, storage_asset_id, occurred_at);

-- ---------------------------------------------------------------------------------------------------------------
-- Gate visits
-- ---------------------------------------------------------------------------------------------------------------

CREATE TABLE ops.gate_visit
(
    port_id         bigint      NOT NULL REFERENCES ref.port (id),
    truck_visit_id  varchar(64) NOT NULL,
    gate_asset_id   uuid        NOT NULL REFERENCES layout.asset (id),
    in_at           timestamptz,
    out_at          timestamptz,
    lane            varchar(32),
    source          varchar(64) NOT NULL,
    quality         varchar(12) NOT NULL CHECK (quality IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
    PRIMARY KEY (port_id, truck_visit_id, gate_asset_id),
    CHECK (in_at IS NULL OR out_at IS NULL OR out_at >= in_at)
);

-- ---------------------------------------------------------------------------------------------------------------
-- Lineage and delivery
-- ---------------------------------------------------------------------------------------------------------------

CREATE TABLE ops.canonical_event
(
    event_id     uuid PRIMARY KEY,
    port_id      bigint       NOT NULL REFERENCES ref.port (id),
    type         varchar(64)  NOT NULL,
    aggregate_id varchar(128) NOT NULL,
    occurred_at  timestamptz  NOT NULL,
    received_at  timestamptz  NOT NULL,
    quality      varchar(12)  NOT NULL CHECK (quality IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
