CREATE TABLE ops.reconciliation_item
(
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id     bigint       NOT NULL REFERENCES ref.port (id),
    kind        varchar(20)  NOT NULL
        CHECK (kind IN ('STALE_EVENT', 'SOURCE_CONFLICT', 'NEGATIVE_BALANCE', 'CAPACITY_EXCEEDED')),
    entity_type varchar(32)  NOT NULL,
    entity_id   varchar(128) NOT NULL,
    event_id    uuid,
    detail      jsonb        NOT NULL DEFAULT '{}',
    status      varchar(8)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED')),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    resolved_by varchar(128),
    resolved_at timestamptz,
    note        text,
    CHECK (status = 'OPEN' OR resolved_by IS NOT NULL)
);

CREATE INDEX reconciliation_item_open ON ops.reconciliation_item (port_id, status, created_at);

CREATE TABLE ops.dead_letter
(
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id     bigint       NOT NULL REFERENCES ref.port (id),
    consumer    varchar(64)  NOT NULL,
    event_id    uuid,
    topic       varchar(200) NOT NULL,
    partition   integer      NOT NULL CHECK (partition >= 0),
    "offset"    bigint       NOT NULL CHECK ("offset" >= 0),
    error       text         NOT NULL,
    attempts    integer      NOT NULL CHECK (attempts >= 1),
    body        jsonb,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    replay_of   bigint REFERENCES ops.dead_letter (id)
);

CREATE INDEX dead_letter_consumer ON ops.dead_letter (port_id, consumer, created_at);

-- ---------------------------------------------------------------------------------------------------------------
-- Immutable rows: the database refuses the change whoever asks (the application role also loses UPDATE and DELETE)
-- ---------------------------------------------------------------------------------------------------------------

CREATE FUNCTION ops.refuse_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION '% rows are immutable: % refused', TG_TABLE_NAME, TG_OP USING ERRCODE = '23514';
END
$$;

CREATE TRIGGER canonical_event_immutable
    BEFORE UPDATE OR DELETE ON ops.canonical_event
    FOR EACH ROW EXECUTE FUNCTION ops.refuse_change();
CREATE TRIGGER cargo_movement_immutable
    BEFORE UPDATE OR DELETE ON ops.cargo_movement
    FOR EACH ROW EXECUTE FUNCTION ops.refuse_change();
CREATE TRIGGER inventory_adjustment_immutable
    BEFORE UPDATE OR DELETE ON ops.inventory_adjustment
    FOR EACH ROW EXECUTE FUNCTION ops.refuse_change();

-- Skipped where castor_app does not exist (Dev Services and tests connect as a single superuser)
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'castor_app') THEN
        RETURN;
    END IF;

    GRANT USAGE ON SCHEMA ops TO castor_app;
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA ops TO castor_app;
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA ops TO castor_app;
    ALTER DEFAULT PRIVILEGES IN SCHEMA ops GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO castor_app;
    ALTER DEFAULT PRIVILEGES IN SCHEMA ops GRANT USAGE, SELECT ON SEQUENCES TO castor_app;

    REVOKE UPDATE, DELETE ON ops.canonical_event, ops.cargo_movement, ops.inventory_adjustment FROM castor_app;
END
$$;
