-- The port record (quay frame, measurement CRS) and the read-only reference features imported from OpenStreetMap (REPLICA-01).
-- Reference features are never edited through the API; they are replaced by the seed or a later import.

CREATE TABLE ref.port (
    code         varchar(32)  PRIMARY KEY CHECK (code ~ '^[a-z0-9-]{2,32}$'),
    name         varchar(120) NOT NULL,
    time_zone    varchar(64)  NOT NULL,
    origin       geometry(Point, 4326) NOT NULL,
    frame_rot_deg numeric(7, 3) NOT NULL,
    measure_srid integer      NOT NULL,
    synthetic    boolean      NOT NULL DEFAULT true
);

CREATE TABLE ref.reference_feature (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_code varchar(32)  NOT NULL REFERENCES ref.port (code),
    osm_ref   varchar(64)  NOT NULL,
    kind      varchar(16)  NOT NULL CHECK (kind IN ('BUILDING', 'ROAD')),
    name      varchar(200),
    height_m  numeric(8, 2) CHECK (height_m >= 0),
    width_m   numeric(8, 2) CHECK (width_m > 0),
    geom      geometry(Geometry, 4326) NOT NULL CHECK (ST_IsValid(geom) AND NOT ST_IsEmpty(geom)),
    source    varchar(32)  NOT NULL,
    accuracy  varchar(16)  NOT NULL CHECK (accuracy IN ('SURVEYED', 'VERIFIED', 'OPERATOR', 'APPROXIMATE')),
    licence   varchar(100) NOT NULL DEFAULT 'ODbL (c) OpenStreetMap contributors',
    UNIQUE (port_code, osm_ref)
);

CREATE INDEX reference_feature_geom_gix ON ref.reference_feature USING gist (geom);
CREATE INDEX reference_feature_port_kind_ix ON ref.reference_feature (port_code, kind);
