-- Reference data (CORE-02): lookups, the port and its frame, control points and read-only background features.
-- Runs as castor_flyway; castor_app gets its rights from the default privileges set in V1.

CREATE TABLE ref.data_source (
    code        varchar(32) PRIMARY KEY,
    name        varchar(120) NOT NULL,
    licence     varchar(120) NOT NULL,
    attribution text         NOT NULL,
    may_persist boolean      NOT NULL,
    may_trace   boolean      NOT NULL,
    url         text
);

CREATE TABLE ref.accuracy_class (
    code       varchar(16) PRIMARY KEY,
    label      varchar(40) NOT NULL,
    colour_hex char(7)     NOT NULL CHECK (colour_hex ~ '^#[0-9A-Fa-f]{6}$'),
    sort_order smallint    NOT NULL
);

CREATE TABLE ref.asset_category (
    code       varchar(16) PRIMARY KEY,
    label      varchar(60) NOT NULL,
    sort_order smallint    NOT NULL
);

CREATE TABLE ref.palette_group (
    code       varchar(16) PRIMARY KEY,
    label      varchar(60) NOT NULL,
    sort_order smallint    NOT NULL
);

CREATE TABLE ref.surface (
    code       varchar(16) PRIMARY KEY,
    label      varchar(40) NOT NULL,
    colour_hex char(7)     NOT NULL CHECK (colour_hex ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE ref.cargo_family (
    code  varchar(16) PRIMARY KEY,
    label varchar(40) NOT NULL
);

CREATE TABLE ref.cargo_type (
    code          varchar(16) PRIMARY KEY,
    name          varchar(60)  NOT NULL,
    family_code   varchar(16)  NOT NULL REFERENCES ref.cargo_family (code),
    base_unit     varchar(8)   NOT NULL CHECK (base_unit IN ('t', 'm3', 'pcs', 'veh', 'TEU')),
    density_t_m3  numeric(6, 3) NOT NULL CHECK (density_t_m3 > 0),
    storage_form  varchar(8)   NOT NULL CHECK (storage_form IN ('PILE', 'STACK', 'SILO', 'TANK', 'UNIT', 'PARKING')),
    max_stack_m   numeric(5, 2) CHECK (max_stack_m > 0),
    repose_deg    numeric(5, 2) CHECK (repose_deg > 0 AND repose_deg < 90),
    colour_hex    char(7)      NOT NULL CHECK (colour_hex ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE ref.ship_class (
    code    varchar(16) PRIMARY KEY,
    name    varchar(60)  NOT NULL,
    kind    varchar(16)  NOT NULL CHECK (kind IN ('GENERAL_CARGO', 'BULK', 'TANKER', 'RORO', 'CONTAINER')),
    loa_m   numeric(6, 1) NOT NULL CHECK (loa_m > 0),
    beam_m  numeric(5, 1) NOT NULL CHECK (beam_m > 0),
    draft_m numeric(5, 1) NOT NULL CHECK (draft_m > 0),
    dwt_t   integer       NOT NULL CHECK (dwt_t > 0)
);

CREATE TABLE ref.port (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                        text NOT NULL UNIQUE
        CONSTRAINT port_code_format CHECK (code ~ '^[a-z0-9-]{2,40}$'),
    name                        varchar(120) NOT NULL,
    city                        varchar(120) NOT NULL,
    time_zone                   varchar(64)  NOT NULL DEFAULT 'Asia/Kuala_Lumpur',
    origin                      geometry(Point, 4326) NOT NULL,
    measure_srid                integer      NOT NULL DEFAULT 3380,
    frame_rot_deg               numeric(8, 3) NOT NULL
        CONSTRAINT port_frame_rot_range CHECK (frame_rot_deg > -360 AND frame_rot_deg < 360),
    extent                      geometry(Polygon, 4326) NOT NULL
        CONSTRAINT port_extent_valid CHECK (ST_IsValid(extent)),
    land_extent                 geometry(Polygon, 4326)
        CONSTRAINT port_land_extent_valid CHECK (ST_IsValid(land_extent)),
    quay_line                   geometry(LineString, 4326)
        CONSTRAINT port_quay_line_valid CHECK (ST_IsValid(quay_line)),
    -- The published layout version; CORE-04 adds the foreign key once layout.layout_version exists.
    current_published_layout_id uuid,
    synthetic                   boolean      NOT NULL DEFAULT true,
    created_at                  timestamptz  NOT NULL DEFAULT now(),
    updated_at                  timestamptz  NOT NULL DEFAULT now(),
    row_version                 bigint       NOT NULL DEFAULT 0
);

-- Foreign keys to spatial_ref_sys and pg_timezone_names are not possible (castor_flyway has no REFERENCES right on
-- them), so a trigger refuses unknown values.
CREATE FUNCTION ref.port_check_lookups() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.spatial_ref_sys WHERE srid = NEW.measure_srid) THEN
        RAISE EXCEPTION 'measure_srid % is not a known spatial reference system', NEW.measure_srid
            USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_timezone_names WHERE name = NEW.time_zone) THEN
        RAISE EXCEPTION 'time_zone % is not an IANA time zone name', NEW.time_zone USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER port_check_lookups
    BEFORE INSERT OR UPDATE OF measure_srid, time_zone ON ref.port
    FOR EACH ROW EXECUTE FUNCTION ref.port_check_lookups();

CREATE TABLE ref.control_point (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id          bigint       NOT NULL REFERENCES ref.port (id),
    code             varchar(40)  NOT NULL,
    name             varchar(120) NOT NULL,
    geom             geometry(Point, 4326) NOT NULL,
    expected_local_x numeric(10, 3) NOT NULL,
    expected_local_y numeric(10, 3) NOT NULL,
    accuracy_code    varchar(16)  NOT NULL REFERENCES ref.accuracy_class (code),
    source_code      varchar(32)  NOT NULL REFERENCES ref.data_source (code),
    UNIQUE (port_id, code)
);

CREATE TABLE ref.import_batch (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id     bigint      NOT NULL REFERENCES ref.port (id),
    source_code varchar(32) NOT NULL REFERENCES ref.data_source (code),
    kind        varchar(16) NOT NULL CHECK (kind IN ('OSM', 'LAYOUT_SEED', 'GEOJSON_IMPORT')),
    started_at  timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    status      varchar(16) NOT NULL DEFAULT 'RUNNING' CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    row_count   integer,
    checksum    char(64),
    note        text
);

CREATE TABLE ref.reference_feature (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id         bigint      NOT NULL REFERENCES ref.port (id),
    kind            varchar(16) NOT NULL
        CHECK (kind IN ('BUILDING', 'ROAD', 'RAIL', 'COASTLINE', 'JETTY', 'WATER', 'LANDUSE')),
    osm_ref         varchar(40) NOT NULL,
    name            varchar(200),
    height_m        numeric(6, 2),
    width_m         numeric(6, 2),
    tags            jsonb       NOT NULL DEFAULT '{}',
    geom            geometry(Geometry, 4326) NOT NULL CHECK (ST_IsValid(geom)),
    source_code     varchar(32) NOT NULL REFERENCES ref.data_source (code),
    import_batch_id bigint      NOT NULL REFERENCES ref.import_batch (id),
    UNIQUE (port_id, osm_ref)
);

CREATE INDEX reference_feature_geom_gist ON ref.reference_feature USING gist (geom);
CREATE INDEX reference_feature_port_kind ON ref.reference_feature (port_id, kind);

