-- ---------------------------------------------------------------------------------------------------------------
-- Storage balances: the book balance, the observed level next to it, and the review flag
-- ---------------------------------------------------------------------------------------------------------------

-- A tank that was observed before any movement has no book balance yet: unknown (NULL), never 0 (R3)
ALTER TABLE ops.storage_inventory
    ALTER COLUMN quantity DROP NOT NULL;

ALTER TABLE ops.storage_inventory
    ADD COLUMN mass_basis           varchar(3) CHECK (mass_basis IN ('WET', 'DRY')),
    -- A movement that would take the balance below zero is recorded, the balance stays and the row waits for a person
    ADD COLUMN needs_reconciliation boolean       NOT NULL DEFAULT false,
    ADD COLUMN level_quantity       numeric(14, 3) CHECK (level_quantity >= 0),
    ADD COLUMN level_unit           varchar(16) CHECK (level_unit IN ('TONNES', 'PIECES', 'CUBIC_METRES', 'VEHICLES')),
    ADD COLUMN level_at             timestamptz,
    ADD COLUMN level_source         varchar(64),
    ADD COLUMN level_quality        varchar(12) CHECK (level_quality IN ('OBSERVED', 'INFERRED', 'SIMULATED')),
    ADD COLUMN level_density_kg_m3  numeric(9, 3) CHECK (level_density_kg_m3 > 0),
    ADD COLUMN level_temperature_c  numeric(6, 2),
    ADD CONSTRAINT storage_inventory_level_complete CHECK (
        (level_quantity IS NULL) = (level_unit IS NULL)
            AND (level_quantity IS NULL) = (level_at IS NULL)
            AND (level_quantity IS NULL) = (level_source IS NULL)
            AND (level_quantity IS NULL) = (level_quality IS NULL));

CREATE INDEX storage_inventory_review ON ops.storage_inventory (port_id) WHERE needs_reconciliation;

-- ---------------------------------------------------------------------------------------------------------------
-- Source precedence: which source is the system of record of a field (README "Decisions: system of record per field")
-- ---------------------------------------------------------------------------------------------------------------

CREATE TABLE ops.source_precedence
(
    port_id     bigint      NOT NULL REFERENCES ref.port (id),
    entity_type varchar(32) NOT NULL,
    field       varchar(32) NOT NULL,
    -- Highest precedence first; lower case source system codes. A source that is not listed ranks below all of them.
    sources     text[]      NOT NULL CHECK (cardinality(sources) >= 1),
    PRIMARY KEY (port_id, entity_type, field)
);

INSERT INTO ops.source_precedence (port_id, entity_type, field, sources)
SELECT p.id, 'VESSEL_CALL', f.field, f.sources
FROM ref.port p
         CROSS JOIN (VALUES ('status', ARRAY ['cbas', 'edic']),
                            ('berth', ARRAY ['cbas', 'edic']),
                            ('eta', ARRAY ['cbas', 'edic']),
                            ('etd', ARRAY ['cbas', 'edic']),
                            ('ata', ARRAY ['edic', 'cbas']),
                            ('atd', ARRAY ['edic', 'cbas'])) AS f (field, sources);

-- Every value of a precedence-ruled field that a source reported, kept whether it was applied or not
CREATE TABLE ops.vessel_call_value
(
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id         bigint       NOT NULL REFERENCES ref.port (id),
    call_id         uuid         NOT NULL REFERENCES ops.vessel_call (id),
    field           varchar(16)  NOT NULL CHECK (field IN ('status', 'berth', 'eta', 'ata', 'etd', 'atd')),
    source          varchar(64)  NOT NULL,
    value           text         NOT NULL,
    occurred_at     timestamptz  NOT NULL,
    source_sequence bigint,
    event_id        uuid         NOT NULL,
    UNIQUE (event_id, field)
);

CREATE INDEX vessel_call_value_latest ON ops.vessel_call_value (call_id, field, source, occurred_at DESC, id DESC);

