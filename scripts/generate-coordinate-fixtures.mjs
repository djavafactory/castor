// Regenerates fixtures/coordinates.json from the SETUP-03 formulas, written out independently of both the
// backend QuayFrame and the frontend lib/geo so the three can be compared. Run: node scripts/generate-coordinate-fixtures.mjs
import { writeFileSync } from 'node:fs'

const frame = { lon0: 101.3066304, lat0: 2.9534057, rotDeg: -120.299 }
const extent = { lonMin: 101.26, lonMax: 101.36, latMin: 2.9, latMax: 3.02 }
const RAD = Math.PI / 180
const mLat = 111132.92 - 559.82 * Math.cos(2 * frame.lat0 * RAD) + 1.175 * Math.cos(4 * frame.lat0 * RAD)
const mLon = 111412.84 * Math.cos(frame.lat0 * RAD) - 93.5 * Math.cos(3 * frame.lat0 * RAD)
const c = Math.cos(frame.rotDeg * RAD)
const s = Math.sin(frame.rotDeg * RAD)
const toLocal = (lon, lat) => {
  const e = (lon - frame.lon0) * mLon
  const n = (lat - frame.lat0) * mLat
  return [e * c + n * s, -e * s + n * c]
}
const toLonLat = (x, y) => [frame.lon0 + (x * c - y * s) / mLon, frame.lat0 + (x * s + y * c) / mLat]

// SETUP-03 control points (approximate survey). x/y are the published local metres.
const controlPoints = [
  ['Main gate', 101.3093602, 2.9518844, -7.9, 346.9],
  ['Coastline point 0', 101.3094176, 2.9579603, -591.2, 13.4],
  ['Coastline point 40', 101.2950289, 2.933553, 2546.1, -6.1],
  ['Coastline point 80', 101.2796057, 2.9065244, 5991.7, 21.3],
].map(([name, lon, lat, x, y]) => ({ name, lon, lat, x, y }))

// 20 reproducible points over the extent (mulberry32 seed 13)
let t = 13
const rnd = () => {
  t = (t + 0x6d2b79f5) | 0
  let r = Math.imul(t ^ (t >>> 15), 1 | t)
  r = (r + Math.imul(r ^ (r >>> 7), 61 | r)) ^ r
  return ((r ^ (r >>> 14)) >>> 0) / 4294967296
}
const points = Array.from({ length: 20 }, () => {
  const lon = +(extent.lonMin + rnd() * (extent.lonMax - extent.lonMin)).toFixed(7)
  const lat = +(extent.latMin + rnd() * (extent.latMax - extent.latMin)).toFixed(7)
  const [x, y] = toLocal(lon, lat)
  return { lon, lat, x, y }
})

// 5 rectangles: anchor is the centre, heading is the true heading of the length axis
const rectSpecs = [
  [101.3066304, 2.9534057, 210.3, 200, 40],
  [101.3094176, 2.9579603, 120.3, 60, 25],
  [101.2950289, 2.9335530, 0, 120, 30],
  [101.2796057, 2.9065244, 45, 80, 80],
  [101.3, 2.99, 300, 15.5, 7.25],
]
const rectangles = rectSpecs.map(([lon, lat, heading, length, width]) => {
  const rot = ((90 - heading - frame.rotDeg + 540) % 360) - 180
  const a = rot * RAD
  const [ax, ay] = toLocal(lon, lat)
  const corners = [[-1, -1], [1, -1], [1, 1], [-1, 1]].map(([sx, sy]) => {
    const dx = (sx * length) / 2
    const dy = (sy * width) / 2
    return toLonLat(ax + dx * Math.cos(a) - dy * Math.sin(a), ay + dx * Math.sin(a) + dy * Math.cos(a))
  })
  return { anchor: [lon, lat], heading, length, width, rotation: rot, corners }
})

const headings = [0, 45, 90, 120.3, 210.3, 300, 359.5].map((h) => ({
  heading: h,
  rotation: ((90 - h - frame.rotDeg + 540) % 360) - 180,
}))

const out = {
  description: 'Shared coordinate fixtures (CORE-01). Generated by scripts/generate-coordinate-fixtures.mjs. Used by backend and frontend tests.',
  frame,
  extent,
  tolerances: { backendVsFrontendM: 0.01, roundTripM: 0.001, controlPointM: 0.1 },
  controlPoints,
  points,
  rectangles,
  headings,
}
writeFileSync(new URL('../fixtures/coordinates.json', import.meta.url), JSON.stringify(out, null, 2) + '\n')
console.log('wrote fixtures/coordinates.json')
