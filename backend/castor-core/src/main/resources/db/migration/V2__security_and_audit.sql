-- Users, roles, login events and the layout audit trail (SETUP-12).
-- Runs as castor_flyway; castor_app gets its rights from the default privileges set in V1.

CREATE TABLE security.user_account (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            varchar(64)  NOT NULL
        CONSTRAINT user_account_username_format CHECK (username ~ '^[a-z0-9._-]{3,64}$'),
    display_name        varchar(120) NOT NULL,
    -- bcrypt in modular crypt format with cost 12 or higher; plaintext and cheaper hashes are refused
    password_hash       varchar(100) NOT NULL
        CONSTRAINT user_account_password_bcrypt CHECK (password_hash ~ '^\$2[aby]\$(1[2-9]|[2-3][0-9])\$'),
    enabled             boolean      NOT NULL DEFAULT true,
    failed_logins       smallint     NOT NULL DEFAULT 0 CHECK (failed_logins >= 0),
    locked_until        timestamptz,
    password_changed_at timestamptz  NOT NULL DEFAULT now(),
    last_login_at       timestamptz,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    row_version         bigint       NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX user_account_username_lower_uq ON security.user_account (lower(username));

CREATE TABLE security.user_role (
    user_id bigint      NOT NULL REFERENCES security.user_account (id) ON DELETE CASCADE,
    role    varchar(16) NOT NULL CHECK (role IN ('VIEWER', 'EDITOR', 'PUBLISHER', 'ADMIN')),
    PRIMARY KEY (user_id, role)
);

CREATE TABLE security.auth_event (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at         timestamptz  NOT NULL DEFAULT now(),
    username   varchar(128) NOT NULL,
    outcome    varchar(16)  NOT NULL CHECK (outcome IN ('SUCCESS', 'FAILURE', 'LOCKED', 'LOGOUT')),
    remote_ip  inet,
    user_agent varchar(300)
);

CREATE INDEX auth_event_at_brin ON security.auth_event USING brin (at);
CREATE INDEX auth_event_username_at ON security.auth_event (lower(username), at DESC);

CREATE TABLE audit.audit_log (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_id           uuid,
    at                timestamptz  NOT NULL DEFAULT now(),
    actor             varchar(128) NOT NULL,
    action            varchar(64)  NOT NULL,
    entity_kind       varchar(64)  NOT NULL,
    entity_id         varchar(128),
    layout_version_id uuid,
    before            jsonb,
    after             jsonb,
    request_id        varchar(64)
);

CREATE INDEX audit_log_port_at ON audit.audit_log (port_id, at DESC);
CREATE INDEX audit_log_entity ON audit.audit_log (entity_id);

-- Login events are append-only for the service too. Skipped where castor_app does not exist (Dev Services, tests).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'castor_app') THEN
        REVOKE UPDATE, DELETE ON security.auth_event FROM castor_app;
    END IF;
END
$$;
