-- Which asset types hold stock: a movement changes a balance only at these (R6: a new type is data, not code)
ALTER TABLE layout.asset_type
    ADD COLUMN holds_stock boolean NOT NULL DEFAULT false;

UPDATE layout.asset_type
SET holds_stock = true
WHERE code IN ('WAREHOUSE_POLY', 'WAREHOUSE', 'TRANSIT_SHED', 'COVERED_BAY', 'LAYDOWN_YARD', 'QUAY_STAGING',
               'STORAGE_PAD', 'SILO', 'STOCKPILE_BAY', 'HOPPER', 'LIQUID_TANK', 'CONTAINER_YARD');
