CREATE INDEX canonical_event_aggregate ON ops.canonical_event (port_id, aggregate_id, occurred_at);

CREATE TABLE ops.processed_event
(
    port_id      bigint       NOT NULL REFERENCES ref.port (id),
    consumer     varchar(64)  NOT NULL,
    event_id     uuid         NOT NULL,
    processed_at timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (consumer, event_id)
);

CREATE TABLE ops.state_change
(
    port_id        bigint       NOT NULL REFERENCES ref.port (id),
    sequence       bigint       NOT NULL CHECK (sequence >= 1),
    entity_type    varchar(32)  NOT NULL,
    entity_id      varchar(128) NOT NULL,
    entity_version bigint       NOT NULL,
    occurred_at    timestamptz  NOT NULL,
    body           jsonb        NOT NULL,
    published_at   timestamptz,
    PRIMARY KEY (port_id, sequence)
);

CREATE INDEX state_change_unpublished ON ops.state_change (port_id, sequence) WHERE published_at IS NULL;

CREATE TABLE ops.stream_cursor
(
    port_id       bigint PRIMARY KEY REFERENCES ref.port (id),
    last_sequence bigint NOT NULL CHECK (last_sequence >= 0)
);

